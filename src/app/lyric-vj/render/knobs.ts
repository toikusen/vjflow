/** What a knob's value depends on: the song (its id) and its mood (calm 0 … lively 1). */
export interface Tuning { song?: number; mood?: number }
const hash = (a: number, b = 0) => {
  const s = Math.sin(a * 127.1 + b * 311.7) * 43758.5453;
  return s - Math.floor(s);
};
/**
 * A move's look in this song: a value in [lo, hi] fixed by the song and the key, so a move reused from another song
 * comes with its own count, size and speed (three meteors here, five there) and keeps them all song long.
 */
export const vary = (e: Tuning, key: string, lo: number, hi: number, lean?: 1 | -1) => {
  if (e.song === undefined) return (lo + hi) / 2;
  let h = e.song;
  for (const c of key) h = (h * 31 + c.charCodeAt(0)) | 0;
  // half the song's own pick, half its mood (calm 0 … lively 1) for the knobs that should follow it
  const u = hash(h % 100003, 7.3), m = e.mood ?? 0.5;
  return lo + (lean ? 0.5 * u + 0.5 * (lean > 0 ? m : 1 - m) : u) * (hi - lo);
};
const varyInt = (e: Tuning, key: string, lo: number, hi: number, lean?: 1 | -1) => Math.round(vary(e, key, lo - 0.49, hi + 0.49, lean));
/** A knob of the move (knobs.ts) in this song. */
export const kn = (e: Tuning, key: string) => {
  const k = KNOBS[key];
  if (!k) throw new Error(`no knob ${key}`);
  return k[3] ? varyInt(e, key, k[1], k[2], k[4]) : vary(e, key, k[1], k[2], k[4]);
};
